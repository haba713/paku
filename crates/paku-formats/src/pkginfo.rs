//! The `.PKGINFO` file at the root of every package archive.
//!
//! ```text
//! # comment
//! pkgname = foo
//! pkgver = 1.0-1
//! depend = bar
//! depend = baz>=2
//! ```

/// Parsed `.PKGINFO`: ordered `key = value` pairs; keys may repeat.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct PkgInfo {
    entries: Vec<(String, String)>,
}

impl PkgInfo {
    /// Parses `.PKGINFO` text. Comment and malformed lines are skipped.
    pub fn parse(text: &str) -> Self {
        let entries = text
            .lines()
            .map(|l| l.trim_end_matches('\r'))
            .filter(|l| !l.trim_start().starts_with('#'))
            .filter_map(|l| l.split_once(" = "))
            .map(|(k, v)| (k.trim().to_string(), v.to_string()))
            .collect();
        PkgInfo { entries }
    }

    /// All values of `key`, in file order.
    pub fn get_all(&self, key: &str) -> Vec<&str> {
        self.entries
            .iter()
            .filter(|(k, _)| k == key)
            .map(|(_, v)| v.as_str())
            .collect()
    }

    /// First value of `key`, if any.
    pub fn get(&self, key: &str) -> Option<&str> {
        self.entries.iter().find(|(k, _)| k == key).map(|(_, v)| v.as_str())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_keys_and_repeats() {
        let p = PkgInfo::parse("# Generated by makepkg\npkgname = foo\npkgver = 1~2.0-1\ndepend = a\ndepend = b>=1\n");
        assert_eq!(p.get("pkgname"), Some("foo"));
        assert_eq!(p.get("pkgver"), Some("1~2.0-1"));
        assert_eq!(p.get_all("depend"), ["a", "b>=1"]);
        assert_eq!(p.get("missing"), None);
    }

    #[test]
    fn value_may_contain_equals() {
        let p = PkgInfo::parse("pkgdesc = a = b\r\n");
        assert_eq!(p.get("pkgdesc"), Some("a = b"));
    }
}
